#!/usr/bin/env python3
"""Build a bootable Pocket8086 CP/M-86 1.1 card image.

    python tools/build.py --sectors 7872            # size of the target card

Produces build/cpm86.img.  Card layout (512-byte sectors):
    LBA 0          boot sector + partition table (type DBh = CP/M-86)
    LBA 1..63      CP/M-86 system image: CCP+BDOS (DR's CPM.H86) + BIOS
    LBA 64..       CP/M drives A:, B:, ... (up to 8 MB each)

The system image is loaded to SYSSEG:0000 and entered at SYSSEG:2500h (INIT).
"""
import argparse
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cpmfs  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src')
BUILD = os.path.join(ROOT, 'build')
TOOLS = os.path.join(ROOT, 'tools')
NASM = os.environ.get('NASM') or next(
    (p for p in (os.path.join(TOOLS, 'nasm-2.16.03', 'nasm.exe'),) if os.path.isfile(p)),
    'nasm')

PART_TYPE = 0xDB        # CP/M-86 / Concurrent CP/M partition type
RESERVED = 64           # sectors before drive A:
SPT = 64                # CP/M logical sectors per track
HOST_PER_TRACK = SPT * 128 // 512
MAX_DRIVE = 16384       # sectors (8 MB, the CP/M 2.2 / CP/M-86 1.1 limit)
MIN_DRIVE = 1024        # sectors (512 KB) - keeps DSM > 255
SYSSEG = 0x0060         # load segment of the system image (above the BIOS data area)
BIOS_OFS = 0x2500


def plan_drives(total, maxdrives):
    avail = total - RESERVED
    drives = []
    lba = RESERVED
    while avail >= MIN_DRIVE and len(drives) < maxdrives:
        size = min(avail, MAX_DRIVE)
        size -= size % HOST_PER_TRACK
        bls = 4096 if size > 8192 else 2048
        blocks = size * 512 // bls
        d = dict(base=lba, sectors=size, tracks=size // HOST_PER_TRACK, bls=bls,
                 dsm=blocks - 1)
        d['bsh'] = {2048: 4, 4096: 5}[bls]
        d['blm'] = bls // 128 - 1
        d['exm'] = {2048: 0, 4096: 1}[bls]
        d['drm'] = (4 * bls) // 32 - 1           # directory = 4 blocks
        d['al0'] = 0xF0
        drives.append(d)
        lba += size
        avail -= size
    if not drives:
        sys.exit('card too small: need at least %d sectors' % (RESERVED + MIN_DRIVE))
    return drives


def gen_layout(drives):
    n = len(drives)
    names = 'A:' if n == 1 else 'A:-%s:' % chr(64 + n)
    sizes = ', '.join('%s: %d KB' % (chr(65 + i), d['sectors'] // 2)
                      for i, d in enumerate(drives))
    L = ['; generated by build.py - do not edit',
         'NDISKS equ %d' % n, 'SPT equ %d' % SPT,
         '%%define DRIVES_MSG "Drives %s (%s)"' % (names, sizes),
         '%macro DRIVE_TABLES 0',
         'drv_base:   dd ' + ', '.join(str(d['base']) for d in drives),
         'drv_tracks: dw ' + ', '.join(str(d['tracks']) for d in drives),
         '%endmacro',
         '%macro DISK_TABLES 0',
         'dpbase:']
    for i in range(n):
        L.append('        dw 0, 0, 0, 0, dirbuf, dpb%d, csv%d, alv%d' % (i, i, i))
    for i, d in enumerate(drives):
        L.append('dpb%d:   dw %d                ; %s: %d KB, %d-byte blocks' % (
            i, SPT, chr(65 + i), d['sectors'] // 2, d['bls']))
        L.append('        db %d, %d, %d           ; BSH, BLM, EXM' % (d['bsh'], d['blm'], d['exm']))
        L.append('        dw %d, %d          ; DSM, DRM' % (d['dsm'], d['drm']))
        L.append('        db 0%02Xh, 0           ; AL0, AL1' % d['al0'])
        L.append('        dw 0, 0             ; CKS (fixed disk), OFF')
    L.append('%endmacro')
    L.append('%macro DISK_BSS 0')
    for i, d in enumerate(drives):
        L.append('alv%d    resb %d' % (i, d['dsm'] // 8 + 1))
        L.append('csv%d:' % i)
    L.append('%endmacro')
    with open(os.path.join(BUILD, 'layout.inc'), 'w') as f:
        f.write('\n'.join(L) + '\n')


def h86_to_bin(path):
    """DR's CPM.H86 (Intel-86 hex) -> CCP+BDOS image, offsets 0000-24FF."""
    img = bytearray(BIOS_OFS)
    for ln in open(path):
        ln = ln.strip()
        if not ln.startswith(':'):
            continue
        b = bytes.fromhex(ln[1:])
        if sum(b) & 0xFF:
            sys.exit('checksum error in %s: %s' % (path, ln))
        n, off, typ = b[0], (b[1] << 8) | b[2], b[3]
        if typ in (0x81, 0x82):                  # code / data (same segment)
            if off + n > BIOS_OFS:
                sys.exit('CPM.H86 data past 2500h')
            img[off:off + n] = b[4:4 + n]
    return bytes(img)


def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode or r.stderr.strip():
        sys.exit((r.stdout + r.stderr).strip())


def write_files(img, d, files):
    region = bytearray(img[d['base'] * 512:(d['base'] + d['sectors']) * 512])
    drv = cpmfs.CpmDrive(region, d)
    for path in files:
        data = open(path, 'rb').read()
        if cpmfs.is_text_name(path):
            data = cpmfs.to_cpm_text(data)
        try:
            drv.write(os.path.basename(path), data)
        except cpmfs.CpmError as e:
            sys.exit('%s: %s' % (path, e))
    img[d['base'] * 512:(d['base'] + d['sectors']) * 512] = region
    return len(drv.files()), (d['dsm'] + 1) - len(drv.free_blocks())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--sectors', type=int, required=True,
                    help='card size in 512-byte sectors')
    ap.add_argument('--files', action='append',
                    help='folder whose files go onto drive A: (repeatable; '
                         'default: cpmfiles and, if present, extras)')
    ap.add_argument('--drives', type=int, default=4, help='max CP/M drives (1-16)')
    ap.add_argument('--out', default=os.path.join(BUILD, 'cpm86.img'))
    a = ap.parse_args()
    os.makedirs(BUILD, exist_ok=True)

    drives = plan_drives(a.sectors, max(1, min(16, a.drives)))
    print('Card: %d sectors (%.1f MB)' % (a.sectors, a.sectors / 2048))
    for i, d in enumerate(drives):
        print('  %s: LBA %d-%d, %d KB, BLS %d, DSM %d, DRM %d' % (
            chr(65 + i), d['base'], d['base'] + d['sectors'] - 1, d['sectors'] // 2,
            d['bls'], d['dsm'], d['drm']))
    gen_layout(drives)

    ccpbdos = h86_to_bin(os.path.join(ROOT, 'dr', 'CPM.H86'))
    bios_bin = os.path.join(BUILD, 'bios86.bin')
    run([NASM, '-f', 'bin', '-I', BUILD + os.sep, '-I', SRC + os.sep, '-o', bios_bin,
         '-l', os.path.join(BUILD, 'bios86.lst'), os.path.join(SRC, 'bios86.asm')])
    bios = open(bios_bin, 'rb').read()
    system = ccpbdos + bios
    nsec = (len(system) + 511) // 512
    if nsec > RESERVED - 1:
        sys.exit('system image too big (%d sectors)' % nsec)
    if SYSSEG * 16 + nsec * 512 > 0x7C00:      # loaded while the boot sector runs
        sys.exit('system image would overlap the boot sector at 7C00h')
    print('  system: CCP+BDOS 0000-24FF, BIOS 2500-%04X (%d bytes), %d sectors' % (
        BIOS_OFS + len(bios) - 1, len(bios), nsec))

    run([NASM, '-f', 'bin', '-DLOADER_SECTORS=%d' % nsec, '-DLOADSEG=%d' % SYSSEG,
         '-DENTRY=%d' % BIOS_OFS, '-o', os.path.join(BUILD, 'boot.bin'),
         os.path.join(SRC, 'boot.asm')])
    boot = bytearray(open(os.path.join(BUILD, 'boot.bin'), 'rb').read())
    assert len(boot) == 512
    first = drives[0]['base']
    count = drives[-1]['base'] + drives[-1]['sectors'] - first
    pe = bytes([0x00, 0xFE, 0xFF, 0xFF, PART_TYPE, 0xFE, 0xFF, 0xFF])
    pe += first.to_bytes(4, 'little') + count.to_bytes(4, 'little')
    boot[0x1BE:0x1CE] = pe

    end = drives[-1]['base'] + drives[-1]['sectors']
    img = bytearray(b'\xe5' * (end * 512))
    img[0:RESERVED * 512] = bytes(RESERVED * 512)
    img[0:512] = boot
    img[512:512 + len(system)] = system

    folders = a.files or [os.path.join(ROOT, 'cpmfiles'), os.path.join(ROOT, 'extras')]
    files = []
    for folder in folders:
        if os.path.isdir(folder):
            files += sorted(os.path.join(folder, f) for f in os.listdir(folder)
                            if os.path.isfile(os.path.join(folder, f)))
        elif a.files:
            sys.exit('no such folder: %s' % folder)
    nent, used = write_files(img, drives[0], files)
    print('  A: %d files, %d of %d blocks used' % (nent, used, drives[0]['dsm'] + 1))
    with open(a.out, 'wb') as f:
        f.write(img)
    print('Wrote %s (%d sectors)' % (a.out, len(img) // 512))


if __name__ == '__main__':
    main()
